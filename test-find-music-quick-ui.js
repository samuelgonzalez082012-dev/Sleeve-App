'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const quick = fs.readFileSync(path.join(root, 'find-music-quick-ui.js'), 'utf8');
const spotifyUi = fs.readFileSync(path.join(root, 'find-music-spotify-ui.js'), 'utf8');
const installer = fs.readFileSync(path.join(root, 'install-find-music.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'find-music.css'), 'utf8');
assert.match(quick, /Paste a link\. Download audio\./);
assert.match(quick, /fmSpotifyUrl/);
assert.match(quick, /find-music-reset/);
assert.match(quick, /fm-advanced-tools/);
assert.match(quick, /addEventListener\('paste'/);
assert.doesNotMatch(quick, /BrowserView|open-store-browser|new WebContentsView/i);
assert.match(spotifyUi, /findMusicSpotifyGetTrack/);
assert.match(spotifyUi, /Download Audio/);
assert.match(spotifyUi, /Fetch Whole Album/);
assert.match(spotifyUi, /findMusicDownloadOpenAudioCollection/);
assert.match(installer, /find-music-quick-ui\.js/);
assert.match(installer, /findMusicSpotifyGetTrack/);
assert.match(css, /fm-quick-download-card/);
console.log('Find Music quick-link workflow tests passed.');
