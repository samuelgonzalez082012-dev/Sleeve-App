'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const converter = require('./find-music-convert-main');

assert.equal(converter.validFormat('mp3'), 'mp3');
assert.equal(converter.validFormat('MP4'), 'mp4');
assert.throws(() => converter.validFormat('wav'), /Choose MP3 audio or MP4 video/);
assert.equal(converter.sourceKind('C:\\Songs\\video.mkv'), 'video');
assert.equal(converter.sourceKind('/home/me/track.FLAC'), 'audio');
assert.equal(converter.sourceKind('/home/me/not-media.txt'), '');
assert.equal(converter.sanitizeBaseName('../../Song: Title?.mp3'), 'Song Title .mp3');
assert.equal(converter.sanitizeBaseName('C:\\Users\\Me\\My Video.mp4'), 'My Video.mp4');
const mp3 = converter.buildFfmpegArgs('input.mp4', 'output.mp3', 'mp3');
assert.deepEqual(mp3.slice(mp3.indexOf('-i'), mp3.indexOf('-i') + 2), ['-i', 'input.mp4']);
assert.ok(mp3.includes('libmp3lame'));
assert.ok(mp3.includes('-vn'));
assert.ok(!mp3.includes('libx264'));
const mp4 = converter.buildFfmpegArgs('input.mov', 'output.mp4', 'mp4');
assert.ok(mp4.includes('libx264'));
assert.ok(mp4.includes('aac'));
assert.ok(mp4.includes('0:v:0'));
assert.throws(() => converter.buildFfmpegArgs('in.mp4', 'out.avi', 'avi'), /Choose MP3 audio or MP4 video/);
assert.equal(converter.parseProgressTime('out_time_ms=3000000'), 3);
assert.equal(converter.parseProgressTime('frame=250'), null);
assert.equal(converter.progressPercent(50, 100), 50);
assert.equal(converter.progressPercent(100, 100), 99);
assert.equal(converter.progressPercent(10, null), null);
const files = new Set([path.join('out', 'Song (Sleeve).mp3')]);
assert.equal(converter.uniqueOutputPath('out', 'Song (Sleeve)', 'mp3', p => files.has(p)), path.join('out', 'Song (Sleeve) (2).mp3'));
console.log('Find Music local conversion core tests passed.');
